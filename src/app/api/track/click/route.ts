import { NextRequest, NextResponse } from 'next/server';
import { container } from '@/core/container';
import { verifyTrackingSignature } from '@/core/security/crypto';
import { checkRateLimit } from '@/core/security/rateLimiter';

export async function GET(req: NextRequest) {
  const clientIp = req.headers.get('x-forwarded-for')?.split(',')[0].trim() || '127.0.0.1';
  
  // Rate limiting: allow up to 120 tracking clicks per minute per IP
  const rateCheck = checkRateLimit('track-click', clientIp, 120, 60 * 1000);
  if (!rateCheck.allowed) {
    return new NextResponse('Too Many Requests', { status: 429 });
  }

  const targetUrl = req.nextUrl.searchParams.get('url');
  const leadId = req.nextUrl.searchParams.get('leadId');
  const campaignId = req.nextUrl.searchParams.get('campaignId');
  const signature = req.nextUrl.searchParams.get('sig');

  try {
    if (leadId) {
      const lead = await container.leadRepo.getLeadById(leadId);
      if (lead) {
        // If lead was only sent, clicking proves they opened the email
        if (lead.status === 'sent') {
          lead.status = 'opened';
          if (lead.customVariables && 'ESTADO' in lead.customVariables) {
            lead.customVariables = { ...lead.customVariables, ESTADO: 'Abierto' };
          }
          await container.leadRepo.updateLead(lead);
        }

        const targetCampId = campaignId || lead.campaignId;
        if (targetCampId) {
          const camp = await container.campaignRepo.getCampaignById(targetCampId);
          if (camp) {
            camp.stats.opportunities = (camp.stats.opportunities || 0) + 1;
            await container.campaignRepo.saveCampaign(camp);
          }
        }

        // Dispatch Webhook event
        container.webhookDispatcher.trigger('lead.clicked', {
          leadId: lead.id,
          leadEmail: lead.email,
          campaignId: targetCampId,
          targetUrl
        }).catch(() => {});
      }
    }
  } catch (err) {
    console.error('Click tracking error:', err);
  }

  // Open Redirect Defense: Validate targetUrl
  if (targetUrl) {
    // 1. Check if HMAC signature matches (tamper-proof tracking links generated by MiSender)
    const isValidSignature = signature
      ? verifyTrackingSignature(signature, targetUrl, leadId || undefined)
      : false;

    // 2. Check if it's a relative URL within our own application
    const isSafeRelative = targetUrl.startsWith('/') && !targetUrl.startsWith('//');

    // 3. Or same-origin URL
    let isSameOrigin = false;
    try {
      const parsed = new URL(targetUrl, req.url);
      if (parsed.origin === req.nextUrl.origin) {
        isSameOrigin = true;
      }
    } catch {}

    if (isValidSignature || isSafeRelative || isSameOrigin) {
      try {
        const dest = new URL(targetUrl, req.url);
        return NextResponse.redirect(dest, 302);
      } catch {}
    }

    // Unsigned or malicious external redirect attempt blocked
    console.warn(`Open Redirect attempt blocked: targetUrl=${targetUrl}`);
    return NextResponse.redirect(new URL('/', req.url), 302);
  }

  return NextResponse.redirect(new URL('/', req.url), 302);
}
